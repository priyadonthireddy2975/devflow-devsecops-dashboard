CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE tracked_repo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL UNIQUE,
    html_url VARCHAR(400) NOT NULL,
    default_branch VARCHAR(100),
    language VARCHAR(60),
    description VARCHAR(500),
    last_synced_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE pipeline_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES tracked_repo (id) ON DELETE CASCADE,
    external_id BIGINT,
    name VARCHAR(200) NOT NULL,
    branch VARCHAR(200),
    commit_sha VARCHAR(64),
    actor VARCHAR(100),
    trigger_event VARCHAR(60),
    status VARCHAR(16) NOT NULL,
    url VARCHAR(500),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    duration_seconds BIGINT,
    CONSTRAINT uq_run_repo_external UNIQUE (repo_id, external_id)
);

CREATE INDEX idx_run_started ON pipeline_run (started_at);
CREATE INDEX idx_run_status ON pipeline_run (status);

CREATE TABLE scan_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL REFERENCES tracked_repo (id) ON DELETE CASCADE,
    tool VARCHAR(60) NOT NULL,
    commit_sha VARCHAR(64),
    run_external_id BIGINT,
    critical INTEGER NOT NULL,
    high INTEGER NOT NULL,
    medium INTEGER NOT NULL,
    low INTEGER NOT NULL,
    report_url VARCHAR(500),
    scanned_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_scan_repo_tool ON scan_result (repo_id, tool, scanned_at);
